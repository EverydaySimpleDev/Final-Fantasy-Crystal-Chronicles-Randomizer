"""
equipment.py - Upgrade paths for the AP world's progressive equipment.

Every tribe has its own weapons and its own "tribal" piece (Clavats a
shield, Lilties gauntlets, Yukes a helm, Selkies a belt); body armor is
shared. The blacksmith scrolls already list the gear in the order the game
hands it out: each scroll record in param.cfd names the piece it makes for
each tribe (fields clavat/lilty/yuke/selkie). Walking the scrolls of a kind
in order and keeping each piece that is stronger than the last one kept
gives one upgrade path per tribe, e.g. for a Clavat's weapon:
Iron Sword 20 -> Steel Blade 25 -> Feather Saber 31 -> Bastard Sword 32
-> Excalibur 33 -> Ragnarok 35.

Item records (72 bytes, see items.py): equiptype (byte 4) is 1 weapon,
4 body armor, 2 shield, 8 gauntlets/helm/belt, 0x10 accessory;
equipability (byte 5) has bit 1 << tribe set for each tribe that can wear
the piece (a scroll can name a piece its tribe can't wear: the Earth Armor
scroll lists Gaia Plate for everyone, but only Clavats can equip it, so a
piece is only kept for tribes that can wear it); the strength or defense
the piece gives is the u16 at byte 6.

Usage:
    py equipment.py show   <game.iso>
    py equipment.py export <game.iso> <worlds/ffcc/equipment_table.py>
"""

import os
import struct
import sys
import tempfile

import ffcc_items
import items as itemstats
import randomizer

TRIBES = ("Clavat", "Lilty", "Yuke", "Selkie")

# AP item name: (equipment slot, first and last scroll of that kind)
# The equipment slot is the index into the caravan's four equipped pieces:
# 0 weapon, 1 body armor, 2 tribal piece.
KINDS = {
    "Progressive Weapon":      (0, [(0x191, 0x19b)]),
    "Progressive Armor":       (1, [(0x19c, 0x1a9)]),
    # shields (Clavat), gauntlets (Lilty), helms (Yuke), belts (Selkie)
    "Progressive Tribal Gear": (2, [(0x1aa, 0x1b2), (0x1b3, 0x1ba), (0x1bb, 0x1c3), (0x1c4, 0x1cc)]),
}

WEARABLE = (1, 2, 4, 8)          # equiptypes of weapons and armor (accessories left out)

# Weapons left in from development that the game never hands out.
DEBUG_ITEMS = {0x0d: "Test1", 0x0e: "Test2"}


def _param(iso):
    path = os.path.join(tempfile.gettempdir(), "equipment_param.cfd")
    randomizer._extract(iso, "dvd/cft/param.cfd", path)
    data = open(path, "rb").read()
    return data, itemstats.find_base(data)


def _record(data, base, item_id):
    return data[base + item_id * itemstats.ENTRY:base + (item_id + 1) * itemstats.ENTRY]


def _u16(record, offset):
    return struct.unpack(">H", record[offset:offset + 2])[0]


def _is_equipment(record):
    """A real weapon or armor piece: not an empty record (type 0) or an accessory."""
    return _u16(record, 0) != 0 and record[4] in WEARABLE


def stats(iso):
    """{item id: strength or defense} for every real weapon and armor piece."""
    data, base = _param(iso)
    return {i: _u16(_record(data, base, i), 6) for i in range(0x01, 0x9f)
            if i not in DEBUG_ITEMS and _is_equipment(_record(data, base, i))}


def paths(iso):
    """{AP item name: [upgrade path per tribe, each [item id, ...]]}."""
    data, base = _param(iso)
    out = {}
    for name, (_, scroll_ranges) in KINDS.items():
        per_tribe = []
        for tribe in range(len(TRIBES)):
            path, best = [], -1
            for first, last in scroll_ranges:
                for scroll in range(first, last + 1):
                    piece = _u16(_record(data, base, scroll), 0x38 + 2 * tribe)
                    if piece in (0, 0xFFFF):
                        continue                 # this scroll makes nothing for this tribe
                    record = _record(data, base, piece)
                    if not record[5] & (1 << tribe):
                        continue                 # this tribe can't wear it
                    power = _u16(record, 6)
                    if power > best:
                        path.append(piece)
                        best = power
            per_tribe.append(path)
        out[name] = per_tribe
    return out


def export(iso, out_path):
    """Write the AP world's equipment_table.py."""
    power = stats(iso)
    upgrade = paths(iso)
    lines = [
        '"""',
        "Generated by equipment.py (Final-Fantasy-Crystal-Chronicles-Randomizer) from the",
        "game files - regenerate instead of editing by hand.",
        "",
        "PATHS[item][tribe] = the pieces the Nth copy of a progressive equipment",
        "item gives, in order (tribes: 0 Clavat, 1 Lilty, 2 Yuke, 3 Selkie).",
        "SLOT[item] = which equipped piece it upgrades (0 weapon, 1 armor, 2 tribal).",
        "POWER[id] = the strength (weapons) or defense (armor) a piece gives.",
        "NAMES[id] = the piece's name.",
        '"""',
        "",
        "SLOT = {",
    ]
    lines += [f"    {name!r}: {slot}," for name, (slot, _) in KINDS.items()]
    lines += ["}", "", "PATHS = {"]
    for name, per_tribe in upgrade.items():
        lines.append(f"    {name!r}: [")
        for tribe, path in zip(TRIBES, per_tribe):
            lines.append(f"        [{', '.join(f'0x{i:02x}' for i in path)}],  # {tribe}")
        lines.append("    ],")
    lines += ["}", "", "POWER = {"]
    lines += [f"    0x{i:02x}: {p}," for i, p in power.items()]
    lines += ["}", "", "NAMES = {"]
    lines += [f"    0x{i:02x}: {ffcc_items.name(i)!r}," for i in power]
    lines += ["}", ""]
    with open(out_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))


def show(iso):
    power = stats(iso)
    for name, per_tribe in paths(iso).items():
        print(name)
        for tribe, path in zip(TRIBES, per_tribe):
            print(f"  {tribe:7s}" + " -> ".join(f"{ffcc_items.name(i)} {power[i]}" for i in path))


if __name__ == "__main__":
    if len(sys.argv) == 3 and sys.argv[1] == "show":
        show(sys.argv[2])
    elif len(sys.argv) == 4 and sys.argv[1] == "export":
        export(sys.argv[2], sys.argv[3])
        print("wrote", sys.argv[3])
    else:
        print(__doc__)
